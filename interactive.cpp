#include "interactive.h"

interactionType getNextInteractionType(interactionType current) {
    switch (current) {
        case NO_INTERACTION: return COLLISION_DETECTED;
        case COLLISION_DETECTED: return PASSENGER_BOARD;
        case PASSENGER_BOARD: return PASSENGER_DROP_OFF;
        case PASSENGER_DROP_OFF: return ADVERTISEMENT_ADD;
        case ADVERTISEMENT_ADD: return ADVERTISEMENT_SUBTRACT;
        case ADVERTISEMENT_SUBTRACT: return NO_INTERACTION;
        default: return current;
    }
};

interactionType interactive::interactionMatrix[OBJ_LENGTH_COUNTER][INTER_LENGTH_COUNTER] = {
    // BUS,          MINIBUS,        DOUBLE_DECKER,  AD_BUS,         CONE,               STOP
    {NO_INTERACTION, NO_INTERACTION, NO_INTERACTION, NO_INTERACTION, COLLISION_DETECTED, PASSENGER_BOARD}, // BUS
    {NO_INTERACTION, NO_INTERACTION, NO_INTERACTION, NO_INTERACTION, COLLISION_DETECTED, PASSENGER_BOARD}, // MINIBUS
    {NO_INTERACTION, NO_INTERACTION, NO_INTERACTION, NO_INTERACTION, COLLISION_DETECTED, PASSENGER_BOARD}, // DOUBLE_DECKER
    {NO_INTERACTION, NO_INTERACTION, NO_INTERACTION, NO_INTERACTION, COLLISION_DETECTED, ADVERTISEMENT_ADD}, // AD_BUS
    {COLLISION_DETECTED, COLLISION_DETECTED, COLLISION_DETECTED, COLLISION_DETECTED, NO_INTERACTION, NO_INTERACTION}, // CONE
    {PASSENGER_DROP_OFF, PASSENGER_DROP_OFF, PASSENGER_DROP_OFF, ADVERTISEMENT_SUBTRACT, NO_INTERACTION, NO_INTERACTION} // STOP
};

interactionType interactive::getInteractionType(objectType source, objectType target) {
    return interactionMatrix[source][target];
}

